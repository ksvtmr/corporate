export function generateQuestions(req: MockRequest): MockResult {
  const ctx = authenticate(req);
  requireCapability(ctx, 'assessments.manage');
  rateLimit(`ai:${ctx.org.id}`, 20);
  const body = asObject(req.body);
  const topic = str(body.topic, 'topic', { required: true, max: 200 })!;
  const count = Number(body.count);
  if (!Number.isInteger(count) || count < 1 || count > 20) throw badRequest('count must be 1-20', { field: 'count', rule: 'range', min: 1, max: 20 });
  const difficulty = ['easy', 'medium', 'hard'].includes(String(body.difficulty)) ? String(body.difficulty) : 'medium';
  const locale = normalizeLocale(body.locale) ?? ctx.locale;
  const points = difficulty === 'hard' ? 15 : difficulty === 'medium' ? 10 : 5;

  const questions = Array.from({ length: count }, (_, i) => {
    if (i % 2 === 1) {
      return { type: 'open_answer', text: fill(pick(locale, QUESTION_TEXT.open), { topic }), points: points * 2, difficulty, topic, source_fragment: pick(locale, QUESTION_TEXT.source) };
    }
    return {
      type: 'single_choice',
      text: fill(pick(locale, QUESTION_TEXT.single), { topic }),
      options: [pick(locale, QUESTION_TEXT.correct), pick(locale, QUESTION_TEXT.wrong1), pick(locale, QUESTION_TEXT.wrong2)],
      correct_option: 0,
      points,
      difficulty,
      topic,
      source_fragment: pick(locale, QUESTION_TEXT.source),
    };
  });
  return ok({ locale, questions });
}
