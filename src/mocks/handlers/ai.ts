const SCOPES = ['all', 'dev', 'security', 'sales'];

function pick(locale: Locale, value: Record<Locale, string>) {
  return value[locale];
}

export function assistantChat(req: MockRequest): MockResult {
  const ctx = authenticate(req);
  requireCapability(ctx, 'ai.assistant');
  rateLimit(`ai:${ctx.org.id}`, 20);
  const body = asObject(req.body);
  const message = str(body.message, 'message', { required: true, max: 2000 })!;
  const scope = typeof body.scope === 'string' && SCOPES.includes(body.scope) ? body.scope : 'all';
  const locale = normalizeLocale(body.locale) ?? ctx.locale;

  if (PROMPT_INJECTION_PATTERNS.some((re) => re.test(message))) {
    return ok({ id: randomId('ans'), locale, answer: pick(locale, INJECTION_REFUSAL), citations: [], not_enough_context: true, blocked: true });
  }

  const q = message.toLowerCase();
  const scored = KNOWLEDGE_BASE.filter((e) => e.scopes.includes(scope))
    .map((e) => ({ e, hits: e.keywords.filter((k) => q.includes(k)).length }))
    .filter((x) => x.hits > 0)
    .sort((a, b) => b.hits - a.hits);

  if (scored.length === 0) {
    return ok({ id: randomId('ans'), locale, answer: pick(locale, NOT_ENOUGH_CONTEXT), citations: [], not_enough_context: true });
  }
  const best = scored[0].e;
  return ok({
    id: randomId('ans'),
    locale,
    answer: resolveLocalized(best.answer, locale).text,
    citations: [
      {
        source_id: best.id,
        title: resolveLocalized(best.citation.title, locale).text,
        section: resolveLocalized(best.citation.section, locale).text,
        snippet: resolveLocalized(best.citation.snippet, locale).text,
      },
    ],
    not_enough_context: false,
  });
}

