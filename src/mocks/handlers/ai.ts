function fill(template: string, vars: Record<string, string>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function generateTrack(req: MockRequest): MockResult {
  const ctx = authenticate(req);
  requireCapability(ctx, 'tracks.manage');
  rateLimit(`ai:${ctx.org.id}`, 20);
  const body = asObject(req.body);
  const role = str(body.role, 'role', { required: true, max: 120 })!;
  const goals = str(body.goals, 'goals', { max: 1000 }) || '';
  const weeks = Math.min(Math.max(Number(body.duration_weeks) || 2, 1), 12);
  const locale = normalizeLocale(body.locale) ?? ctx.locale;
  const department_id = str(body.department_id, 'department_id');
  if (department_id && !ctx.db.departments.some((d) => d.id === department_id && d.organization_id === ctx.org.id)) {
    throw badRequest('Unknown department', { field: 'department_id', rule: 'exists' });
  }

  const goalItems = goals.split(/[,;\n.]+/).map((g) => g.trim()).filter((g) => g.length > 2).slice(0, 4);
  const blocks: Array<{ type: BlockType; title: string; duration_minutes: number; transition_rule: Rule }> = [
    { type: 'material', title: pick(locale, TRACK_TEXT.intro), duration_minutes: 60, transition_rule: 'sequential' },
    ...goalItems.map((goal) => ({ type: 'material' as const, title: fill(pick(locale, TRACK_TEXT.goal), { goal }), duration_minutes: 45, transition_rule: 'sequential' as const })),
    { type: 'flashcards', title: pick(locale, TRACK_TEXT.terms), duration_minutes: 30, transition_rule: 'free' },
    { type: 'video', title: pick(locale, TRACK_TEXT.review), duration_minutes: 45, transition_rule: 'must_complete_previous' },
    { type: 'test', title: pick(locale, TRACK_TEXT.test), duration_minutes: 30, transition_rule: 'min_score_70' },
    { type: 'open_question', title: fill(pick(locale, TRACK_TEXT.practice), { role }), duration_minutes: 60 * Math.min(weeks, 4), transition_rule: 'must_complete_previous' },
    { type: 'acknowledgment', title: pick(locale, TRACK_TEXT.ack), duration_minutes: 10, transition_rule: 'must_complete_previous' },
  ];
  const minutes = blocks.reduce((s, b) => s + b.duration_minutes, 0);
  return ok({
    locale,
    title: fill(pick(locale, TRACK_TEXT.title), { role }),
    description: fill(pick(locale, TRACK_TEXT.description), { role }),
    department_id: department_id ?? null,
    total_duration_hours: Math.max(1, Math.round(minutes / 60)),
    blocks,
  });
}

